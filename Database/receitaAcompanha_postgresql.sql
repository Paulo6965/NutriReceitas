CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(191) NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NULL UNIQUE,
    locale VARCHAR(10) DEFAULT 'pt-BR',
    timezone VARCHAR(64) DEFAULT 'America/Sao_Paulo',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    preference_key VARCHAR(100) NOT NULL,
    preference_value VARCHAR(255) NULL,
    value_json JSON NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_preference UNIQUE (user_id, preference_key),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    normalized_name VARCHAR(150) NOT NULL,
    description TEXT NULL,
    category VARCHAR(100) NULL,
    calories_per_100g DECIMAL(10,2) NULL,
    protein_per_100g DECIMAL(10,2) NULL,
    carbs_per_100g DECIMAL(10,2) NULL,
    fat_per_100g DECIMAL(10,2) NULL,
    fiber_per_100g DECIMAL(10,2) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ingredient_name UNIQUE (normalized_name)
);
CREATE INDEX IF NOT EXISTS idx_ingredient_category ON ingredients(category);

CREATE TABLE IF NOT EXISTS ingredient_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL,
    alias VARCHAR(150) NOT NULL,
    normalized_alias VARCHAR(150) NOT NULL,
    CONSTRAINT uq_alias UNIQUE (normalized_alias),
    FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity DECIMAL(12,3) NULL,
    unit VARCHAR(30) NULL,
    expires_at DATE NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'low', 'expired', 'consumed')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (ingredient_id) REFERENCES ingredients(id)
);
CREATE INDEX IF NOT EXISTS idx_user_ingredients ON user_ingredients(user_id, status);
CREATE INDEX IF NOT EXISTS idx_expiration ON user_ingredients(user_id, expires_at);

CREATE TABLE IF NOT EXISTS recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NULL,
    cuisine VARCHAR(100) NULL,
    meal_type VARCHAR(100) NULL,
    difficulty VARCHAR(10) DEFAULT 'easy' CHECK (difficulty IN ('easy', 'medium', 'hard')),
    prep_time_minutes SMALLINT NULL CHECK (prep_time_minutes >= 0),
    cook_time_minutes SMALLINT NULL CHECK (cook_time_minutes >= 0),
    total_time_minutes SMALLINT NULL CHECK (total_time_minutes >= 0),
    servings DECIMAL(5,2) NULL,
    instructions TEXT NULL,
    source VARCHAR(255) NULL,
    source_url VARCHAR(500) NULL,
    status VARCHAR(10) DEFAULT 'active' CHECK (status IN ('active', 'draft', 'archived')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ft_recipe_search ON recipes USING GIN (to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(description, '')));

CREATE TABLE IF NOT EXISTS recipe_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity DECIMAL(12,3) NULL,
    unit VARCHAR(30) NULL,
    optional BOOLEAN NOT NULL DEFAULT FALSE,
    preparation VARCHAR(255) NULL,
    sort_order SMALLINT DEFAULT 0 CHECK (sort_order >= 0),
    FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
    FOREIGN KEY (ingredient_id) REFERENCES ingredients(id)
);
CREATE INDEX IF NOT EXISTS idx_recipe ON recipe_ingredients(recipe_id);
CREATE INDEX IF NOT EXISTS idx_ingredient ON recipe_ingredients(ingredient_id);

CREATE TABLE IF NOT EXISTS tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS recipe_tags (
    recipe_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    PRIMARY KEY (recipe_id, tag_id),
    FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
    FOREIGN KEY (tag_id) REFERENCES tags(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS dietary_restrictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    type VARCHAR(50) NULL
);

CREATE TABLE IF NOT EXISTS user_dietary_restrictions (
    user_id BIGINT NOT NULL,
    restriction_id BIGINT NOT NULL,
    severity VARCHAR(10) DEFAULT 'avoid' CHECK (severity IN ('preference', 'avoid', 'strict')),
    PRIMARY KEY (user_id, restriction_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (restriction_id) REFERENCES dietary_restrictions(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_ingredient_preferences (
    user_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    preference VARCHAR(10) NOT NULL DEFAULT 'neutral' CHECK (preference IN ('favorite', 'liked', 'neutral', 'disliked', 'avoid')),
    score DECIMAL(5,2) NULL,
    PRIMARY KEY (user_id, ingredient_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_recipe_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recipe_id BIGINT NOT NULL,
    event_type VARCHAR(12) NOT NULL CHECK (event_type IN ('viewed', 'recommended', 'saved', 'cooked', 'skipped')),
    rating SMALLINT NULL CHECK (rating BETWEEN 0 AND 255),
    notes TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (recipe_id) REFERENCES recipes(id)
);
CREATE INDEX IF NOT EXISTS idx_user_history ON user_recipe_history(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_recipe_history ON user_recipe_history(recipe_id);

CREATE TABLE IF NOT EXISTS user_favorite_recipes (
    user_id BIGINT NOT NULL,
    recipe_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, recipe_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS recipe_nutrition (
    recipe_id BIGINT PRIMARY KEY,
    calories DECIMAL(10,2) NULL,
    protein_g DECIMAL(10,2) NULL,
    carbohydrates_g DECIMAL(10,2) NULL,
    fat_g DECIMAL(10,2) NULL,
    fiber_g DECIMAL(10,2) NULL,
    sodium_mg DECIMAL(10,2) NULL,
    sugar_g DECIMAL(10,2) NULL,
    FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS meal_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recipe_id BIGINT NULL,
    meal_type VARCHAR(10) NOT NULL CHECK (meal_type IN ('breakfast', 'lunch', 'dinner', 'snack', 'other')),
    consumed_at TIMESTAMP NOT NULL,
    servings DECIMAL(6,2) DEFAULT 1,
    notes TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (recipe_id) REFERENCES recipes(id)
);
CREATE INDEX IF NOT EXISTS idx_user_meals ON meal_logs(user_id, consumed_at);

CREATE TABLE IF NOT EXISTS user_nutrition_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    calories_target DECIMAL(10,2) NULL,
    protein_target_g DECIMAL(10,2) NULL,
    carbs_target_g DECIMAL(10,2) NULL,
    fat_target_g DECIMAL(10,2) NULL,
    fiber_target_g DECIMAL(10,2) NULL,
    start_date DATE NULL,
    end_date DATE NULL,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_active_goal ON user_nutrition_goals(user_id, active);

CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    channel VARCHAR(5) DEFAULT 'chat' CHECK (channel IN ('chat', 'voice', 'api')),
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at TIMESTAMP NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_user_conversations ON conversations(user_id, last_message_at);

CREATE TABLE IF NOT EXISTS conversation_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    role VARCHAR(9) NOT NULL CHECK (role IN ('user', 'assistant', 'system', 'tool')),
    content TEXT NOT NULL,
    tool_name VARCHAR(100) NULL,
    metadata JSON NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (conversation_id) REFERENCES conversations(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_conversation_messages ON conversation_messages(conversation_id, created_at);

CREATE TABLE IF NOT EXISTS agent_memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    memory_type VARCHAR(50) NOT NULL,
    memory_key VARCHAR(150) NOT NULL,
    value_text TEXT NULL,
    value_json JSON NULL,
    confidence DECIMAL(5,4) NULL,
    source_conversation_id BIGINT NULL,
    expires_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_user_memory ON agent_memories(user_id, memory_type, memory_key);

-- PostgreSQL replacement for MySQL's ON UPDATE CURRENT_TIMESTAMP.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER users_set_updated_at BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER user_preferences_set_updated_at BEFORE UPDATE ON user_preferences
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER user_ingredients_set_updated_at BEFORE UPDATE ON user_ingredients
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER recipes_set_updated_at BEFORE UPDATE ON recipes
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE TRIGGER agent_memories_set_updated_at BEFORE UPDATE ON agent_memories
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
